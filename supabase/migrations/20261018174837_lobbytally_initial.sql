CREATE FUNCTION sync_feed_feature_evidence()
RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $function$
BEGIN
    IF TG_OP <> 'INSERT' THEN
        DELETE FROM feed_feature_evidence WHERE evidence_id = OLD.evidence_id;
    END IF;
    IF TG_OP <> 'DELETE' THEN
        IF NEW.is_active = 1 AND NEW.feature_name IN (
            'matchmaking_core', 'public_world_dependency',
            'service_shutdown_risk', 'catalog_taxonomy'
        ) THEN
            INSERT INTO feed_feature_evidence (
                evidence_id, app_id, feature_name, value_json, confidence,
                observed_at_ms, expires_at_ms
            ) VALUES (
                NEW.evidence_id, NEW.app_id, NEW.feature_name, NEW.value_json,
                NEW.confidence, NEW.observed_at_ms, NEW.expires_at_ms
            )
            ON CONFLICT (evidence_id) DO UPDATE SET
                app_id = excluded.app_id,
                feature_name = excluded.feature_name,
                value_json = excluded.value_json,
                confidence = excluded.confidence,
                observed_at_ms = excluded.observed_at_ms,
                expires_at_ms = excluded.expires_at_ms;
        END IF;
    END IF;
    RETURN NULL;
END;
$function$;

CREATE TRIGGER trg_feed_feature_evidence_insert
AFTER INSERT ON feature_evidence
FOR EACH ROW EXECUTE FUNCTION sync_feed_feature_evidence();
CREATE TRIGGER trg_feed_feature_evidence_update
AFTER UPDATE ON feature_evidence
FOR EACH ROW EXECUTE FUNCTION sync_feed_feature_evidence();
CREATE TRIGGER trg_feed_feature_evidence_delete
AFTER DELETE ON feature_evidence
FOR EACH ROW EXECUTE FUNCTION sync_feed_feature_evidence();

-- Application tables are backend-only, even if someone later exposes this schema.
-- Table owners and BYPASSRLS service database roles retain direct SQL access.
DO $permissions$
DECLARE
    app_schema TEXT := current_schema();
    app_table RECORD;
    api_role TEXT;
BEGIN
    FOR app_table IN
        SELECT relation.relname
        FROM pg_class relation
        JOIN pg_namespace namespace ON namespace.oid = relation.relnamespace
        WHERE namespace.nspname = app_schema AND relation.relkind IN ('r', 'p')
    LOOP
        EXECUTE format('ALTER TABLE %I.%I ENABLE ROW LEVEL SECURITY', app_schema, app_table.relname);
    END LOOP;
    EXECUTE format('REVOKE ALL ON SCHEMA %I FROM PUBLIC', app_schema);
    EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA %I FROM PUBLIC', app_schema);
    EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA %I FROM PUBLIC', app_schema);
    EXECUTE format('REVOKE ALL ON ALL FUNCTIONS IN SCHEMA %I FROM PUBLIC', app_schema);
    FOR api_role IN SELECT rolname FROM pg_roles WHERE rolname IN ('anon', 'authenticated') LOOP
        EXECUTE format('REVOKE ALL ON SCHEMA %I FROM %I', app_schema, api_role);
        EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA %I FROM %I', app_schema, api_role);
        EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA %I FROM %I', app_schema, api_role);
        EXECUTE format('REVOKE ALL ON ALL FUNCTIONS IN SCHEMA %I FROM %I', app_schema, api_role);
    END LOOP;
END;
$permissions$;

