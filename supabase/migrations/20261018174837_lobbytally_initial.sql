-- Fresh PostgreSQL baseline for Vercel + Supabase.
-- This consolidates the final domain schema of SQLite migrations 0001..0030.
-- Existing SQLite data is intentionally not imported.
-- The backend connects directly to the private mpgs schema; it is not a Data API schema.
-- Tests set the session's mpgs.schema setting to an isolated schema before applying this file.
DO $schema$
DECLARE
    app_schema TEXT := coalesce(nullif(current_setting('mpgs.schema', true), ''), 'mpgs');
BEGIN
    EXECUTE format('CREATE SCHEMA IF NOT EXISTS %I', app_schema);
    PERFORM set_config('search_path', format('%I, public, extensions', app_schema), false);
END;
$schema$;

DO $extension$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_trgm') THEN
        -- Test schemas can initialize in parallel before this database has pg_trgm.
        PERFORM pg_advisory_xact_lock(hashtextextended('mpgs:extension:pg_trgm', 0));
        CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;
    END IF;
END;
$extension$;

