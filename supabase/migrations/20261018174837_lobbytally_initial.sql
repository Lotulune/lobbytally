-- Lock each affected app in a stable order before rebuilding its latest review.
-- This keeps concurrent snapshots and deletes from leaving a stale projection.
CREATE FUNCTION sync_latest_review_snapshots()
RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $function$
DECLARE
    affected_app_ids BIGINT[];
    affected_app_id BIGINT;
BEGIN
    IF TG_OP = 'INSERT' THEN
        affected_app_ids := ARRAY[NEW.app_id];
    ELSIF TG_OP = 'DELETE' THEN
        affected_app_ids := ARRAY[OLD.app_id];
    ELSE
        affected_app_ids := ARRAY[OLD.app_id, NEW.app_id];
    END IF;

    PERFORM app_id FROM apps
    WHERE app_id = ANY(affected_app_ids)
    ORDER BY app_id FOR NO KEY UPDATE;

    FOR affected_app_id IN SELECT DISTINCT unnest(affected_app_ids) LOOP
        DELETE FROM latest_review_snapshots WHERE app_id = affected_app_id;
        INSERT INTO latest_review_snapshots (
            app_id, region_scope, language_scope, captured_at_ms,
            total_positive, total_negative, total_reviews, wilson_lower
        )
        SELECT app_id, region_scope, language_scope, captured_at_ms,
               total_positive, total_negative, total_reviews, wilson_lower
        FROM review_snapshots
        WHERE app_id = affected_app_id
        ORDER BY captured_at_ms DESC, language_scope ASC, region_scope ASC
        LIMIT 1
        ON CONFLICT (app_id) DO UPDATE SET
            region_scope = excluded.region_scope,
            language_scope = excluded.language_scope,
            captured_at_ms = excluded.captured_at_ms,
            total_positive = excluded.total_positive,
            total_negative = excluded.total_negative,
            total_reviews = excluded.total_reviews,
            wilson_lower = excluded.wilson_lower;
    END LOOP;
    RETURN NULL;
END;
$function$;

